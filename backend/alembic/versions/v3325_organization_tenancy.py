"""users - organizations, memberships, and the ledger that makes the backfill reversible.

Three new tables and one additive nullable column. **No data rewrite lives here**,
which is a decision and not an omission: this product does not run
``alembic upgrade head`` against an existing database. ``postgres_auto_migrate``
creates missing tables and then stamps head, so a forward transformation written
into ``upgrade()`` would never execute anywhere, and the install would look
migrated while every ``tenant_id`` still named a user. The transformation lives in
``app/modules/users/repairs.py`` as the boot repair
``users_tenant_organization_backfill``, registered in the data-repair registry, so
it runs on every boot and therefore on every install shape: upgraded, freshly
created, or restored from a backup taken before organizations existed.

What this revision owns is the schema the repair writes into, and the downgrade
that undoes what the repair did:

* ``oe_users_organization`` - the tenant (ADR 005).
* ``oe_users_membership`` - ``Organization -> Membership -> User``.
* ``oe_users_tenant_backfill`` - one row per value the repair overwrote, holding
  the previous value including ``NULL``. ``downgrade()`` replays it, so a
  populated database goes back to the ownership it had rather than losing it
  along with the tables.
* ``oe_projects_project.organization_id`` - the ``Organization -> Project`` edge,
  nullable and left nullable: this table carries no ``tenant_id``, so no row-level
  policy is attached to it, and tightening the column is a decision to make once
  the readiness report says every row has an owner.

Every step is inspector-guarded, so a database whose tables ``create_all``
already built reaches this revision and does nothing.

Revision ID: v3325_organization_tenancy
Revises: v199_subcontractor_contact_link
Create Date: 2026-10-29
"""

from __future__ import annotations

from collections.abc import Sequence

import sqlalchemy as sa
from alembic import op

from app.database import GUID

revision: str = "v3325_organization_tenancy"
down_revision: str | Sequence[str] | None = "v199_subcontractor_contact_link"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

_ORGANIZATION = "oe_users_organization"
_MEMBERSHIP = "oe_users_membership"
_LEDGER = "oe_users_tenant_backfill"
_USER = "oe_users_user"
_PROJECT = "oe_projects_project"
_PROJECT_COLUMN = "organization_id"

# Names produced by the naming convention in ``app.database`` for the ORM
# declarations of the same objects. Spelled out here so that a database built by
# this revision and one built by ``create_all`` are indistinguishable to the next
# autogenerated diff.
_UQ_ORGANIZATION_SLUG = "uq_oe_users_organization_slug"
_IX_ORGANIZATION_SLUG = "ix_oe_users_organization_slug"
_UQ_MEMBERSHIP = "uq_oe_users_membership_user_org"
_IX_MEMBERSHIP_USER = "ix_oe_users_membership_user_id"
_IX_MEMBERSHIP_ORGANIZATION = "ix_oe_users_membership_organization_id"
_FK_MEMBERSHIP_USER = "fk_oe_users_membership_user_id_oe_users_user"
_FK_MEMBERSHIP_ORGANIZATION = "fk_oe_users_membership_organization_id_oe_users_organization"
_UQ_LEDGER = "uq_oe_users_tenant_backfill_row"
_IX_LEDGER_TABLE = "ix_oe_users_tenant_backfill_table_name"
_IX_PROJECT_ORGANIZATION = "ix_oe_projects_project_organization_id"
_FK_PROJECT_ORGANIZATION = "fk_oe_projects_project_organization_id_oe_users_organization"


def _tables(bind) -> set[str]:
    return set(sa.inspect(bind).get_table_names())


def _columns(bind, table: str) -> set[str]:
    return {c["name"] for c in sa.inspect(bind).get_columns(table)}


def _indexes(bind, table: str) -> set[str]:
    return {i["name"] for i in sa.inspect(bind).get_indexes(table)}


def _constraints(bind, table: str) -> set[str]:
    return {c["name"] for c in sa.inspect(bind).get_unique_constraints(table)}


def _foreign_keys(bind, table: str) -> set[str]:
    return {f["name"] for f in sa.inspect(bind).get_foreign_keys(table)}


def upgrade() -> None:
    """Create the tenancy schema when it is missing. Additive; no data rewrite."""
    bind = op.get_bind()
    tables = _tables(bind)
    supports_fk = bind.dialect.name != "sqlite"

    # ── oe_users_organization ────────────────────────────────────────────
    if _ORGANIZATION not in tables:
        op.create_table(
            _ORGANIZATION,
            sa.Column("id", GUID(), primary_key=True, nullable=False),
            sa.Column("name", sa.String(255), nullable=False),
            # Unique, and load-bearing: two boots racing to establish the
            # install's organization collide here on purpose, and the loser
            # adopts the winner's row. The repair and the token mint both rely on
            # it, which is why it is a constraint and not an application-level
            # check.
            sa.Column("slug", sa.String(64), nullable=False),
            sa.Column("status", sa.String(16), nullable=False),
            sa.Column("created_at", sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()),
            sa.Column("updated_at", sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()),
        )
        tables.add(_ORGANIZATION)
    if _UQ_ORGANIZATION_SLUG not in _constraints(bind, _ORGANIZATION):
        op.create_unique_constraint(_UQ_ORGANIZATION_SLUG, _ORGANIZATION, ["slug"])
    if _IX_ORGANIZATION_SLUG not in _indexes(bind, _ORGANIZATION):
        op.create_index(_IX_ORGANIZATION_SLUG, _ORGANIZATION, ["slug"])

    # ── oe_users_membership ──────────────────────────────────────────────
    if _MEMBERSHIP not in tables:
        op.create_table(
            _MEMBERSHIP,
            sa.Column("id", GUID(), primary_key=True, nullable=False),
            sa.Column("user_id", GUID(), nullable=False),
            sa.Column("organization_id", GUID(), nullable=False),
            sa.Column("role", sa.String(50), nullable=False),
            sa.Column("status", sa.String(16), nullable=False),
            sa.Column("is_default", sa.Boolean(), nullable=False),
            sa.Column("created_at", sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()),
            sa.Column("updated_at", sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()),
        )
        tables.add(_MEMBERSHIP)
    if _UQ_MEMBERSHIP not in _constraints(bind, _MEMBERSHIP):
        op.create_unique_constraint(_UQ_MEMBERSHIP, _MEMBERSHIP, ["user_id", "organization_id"])
    if _IX_MEMBERSHIP_USER not in _indexes(bind, _MEMBERSHIP):
        op.create_index(_IX_MEMBERSHIP_USER, _MEMBERSHIP, ["user_id"])
    if _IX_MEMBERSHIP_ORGANIZATION not in _indexes(bind, _MEMBERSHIP):
        op.create_index(_IX_MEMBERSHIP_ORGANIZATION, _MEMBERSHIP, ["organization_id"])
    if supports_fk:
        existing = _foreign_keys(bind, _MEMBERSHIP)
        if _USER in tables and _FK_MEMBERSHIP_USER not in existing:
            op.create_foreign_key(_FK_MEMBERSHIP_USER, _MEMBERSHIP, _USER, ["user_id"], ["id"], ondelete="CASCADE")
        if _FK_MEMBERSHIP_ORGANIZATION not in existing:
            op.create_foreign_key(
                _FK_MEMBERSHIP_ORGANIZATION,
                _MEMBERSHIP,
                _ORGANIZATION,
                ["organization_id"],
                ["id"],
                ondelete="CASCADE",
            )

    # ── oe_users_tenant_backfill ─────────────────────────────────────────
    if _LEDGER not in tables:
        op.create_table(
            _LEDGER,
            sa.Column("id", GUID(), primary_key=True, nullable=False),
            sa.Column("table_name", sa.String(128), nullable=False),
            sa.Column("row_id", sa.String(36), nullable=False),
            # VARCHAR(64): the widest ``tenant_id`` in the schema is
            # ``oe_governance_catalogue`` and
            # ``oe_procurement_concept_framework``. A ledger that truncated the
            # value it was keeping would restore the wrong one, which is worse
            # than no ledger at all.
            sa.Column("previous_tenant_id", sa.String(64), nullable=True),
            sa.Column("created_at", sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()),
            sa.Column("updated_at", sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()),
        )
        tables.add(_LEDGER)
    if _UQ_LEDGER not in _constraints(bind, _LEDGER):
        op.create_unique_constraint(_UQ_LEDGER, _LEDGER, ["table_name", "row_id"])
    if _IX_LEDGER_TABLE not in _indexes(bind, _LEDGER):
        op.create_index(_IX_LEDGER_TABLE, _LEDGER, ["table_name"])

    # ── oe_projects_project.organization_id ──────────────────────────────
    if _PROJECT in tables and _PROJECT_COLUMN not in _columns(bind, _PROJECT):
        op.add_column(_PROJECT, sa.Column(_PROJECT_COLUMN, GUID(), nullable=True))
        if supports_fk and _ORGANIZATION in _tables(bind):
            op.create_foreign_key(
                # ``SET NULL``: removing an organization must not remove its
                # projects. A project with no organization can be re-pointed by
                # the boot repair or by an administrator; a deleted one cannot be
                # recovered.
                _FK_PROJECT_ORGANIZATION,
                _PROJECT,
                _ORGANIZATION,
                [_PROJECT_COLUMN],
                ["id"],
                ondelete="SET NULL",
            )
    if _PROJECT in tables and _IX_PROJECT_ORGANIZATION not in _indexes(bind, _PROJECT):
        op.create_index(_IX_PROJECT_ORGANIZATION, _PROJECT, [_PROJECT_COLUMN])


def downgrade() -> None:
    """Put the data back the way it was, then remove the schema.

    The ledger is replayed *first*, while the tables it names still exist. Order
    matters here in a way it usually does not in a downgrade: dropping
    ``oe_users_tenant_backfill`` before replaying it would remove the only record
    of what the boot repair overwrote, and the install would keep the
    organizations in its ``tenant_id`` columns with nothing left to say what was
    there before.

    Rows written after the repair ran are not in the ledger and cannot be
    restored - that is the named limit of this downgrade, recorded in ADR 005
    rather than discovered by whoever runs it.
    """
    bind = op.get_bind()
    tables = _tables(bind)
    supports_fk = bind.dialect.name != "sqlite"

    if _LEDGER in tables:
        entries = bind.execute(sa.text(f"SELECT table_name, row_id, previous_tenant_id FROM {_LEDGER}")).fetchall()
        for table_name, row_id, previous in entries:
            if table_name not in tables:
                continue
            if "tenant_id" not in _columns(bind, table_name):
                continue
            # ``id`` is a ``GUID()``, which stores as VARCHAR(36) on every
            # dialect, so this needs no cast and works the same everywhere.
            bind.execute(
                sa.text(f'UPDATE "{table_name}" SET tenant_id = :previous WHERE id = :row_id'),
                {"previous": previous, "row_id": row_id},
            )

    if _PROJECT in tables:
        if _IX_PROJECT_ORGANIZATION in _indexes(bind, _PROJECT):
            op.drop_index(_IX_PROJECT_ORGANIZATION, table_name=_PROJECT)
        if _PROJECT_COLUMN in _columns(bind, _PROJECT):
            if supports_fk and _FK_PROJECT_ORGANIZATION in _foreign_keys(bind, _PROJECT):
                op.drop_constraint(_FK_PROJECT_ORGANIZATION, _PROJECT, type_="foreignkey")
            op.drop_column(_PROJECT, _PROJECT_COLUMN)

    for table in (_LEDGER, _MEMBERSHIP, _ORGANIZATION):
        if table not in tables:
            continue
        # Indexes and constraints go with the table, but the foreign keys pointing
        # *at* it do not: drop them explicitly so the DROP is not refused by a
        # dependency the inspector can see and this function ignored.
        if table == _MEMBERSHIP and supports_fk:
            for name in (_FK_MEMBERSHIP_USER, _FK_MEMBERSHIP_ORGANIZATION):
                if name in _foreign_keys(bind, _MEMBERSHIP):
                    op.drop_constraint(name, _MEMBERSHIP, type_="foreignkey")
        op.drop_table(table)
        tables.discard(table)
